function buildLevel(grade, tiers) {
  const tierObjs = Object.entries(tiers).map(([title, skills], ti) => ({
    id: `L${grade}.T${ti + 1}`,
    title,
    atomic_skills: skills.map(([key, stitle, desc, capsTopic, templates, et, ed, ex, rec]) => ({
      id: `ECON.G${grade}.T${ti + 1}.${key}.A1`,
      bank_skill_id: `ECON.G${grade}.T${ti + 1}.${key}.A1`,
      title: stitle,
      description: desc,
      caps_term: `G${grade} T${ti + 1}`,
      caps_topic: capsTopic,
      prerequisites: [],
      templates,
      error_signatures: [{ type: et, description: ed, example: ex }],
      recovery_strategy: rec,
      mastery_criteria: { ...MC },
    })),
  }));
  return tierObjs;
}

