// Regenerates lib/afrikaans-skill-stats.ts from data/afrikaans-question-bank.json.
// Run via: node scripts/regen-afrikaans-skill-stats.mjs
//
// The full bank (~1.3 MB) is only needed server-side in lib/afrikaans-selector.ts.
// AfrikaansSession.tsx (client component) only reads two scalar values per skill,
// so we ship just those — keeps the bank out of the client bundle.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const bankFile = path.join(repoRoot, "data", "afrikaans-question-bank.json");
const outFile = path.join(repoRoot, "lib", "afrikaans-skill-stats.ts");

let raw = fs.readFileSync(bankFile, "utf-8");
if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1);
const bank = JSON.parse(raw);

const stats = {};
for (const [skillId, skill] of Object.entries(bank.skills)) {
  stats[skillId] = {
    itemCount: Array.isArray(skill.questions) ? skill.questions.length : 0,
    passThreshold: typeof skill.pass_threshold === "number" ? skill.pass_threshold : 0.6,
  };
}

const sortedIds = Object.keys(stats).sort();
const body = sortedIds
  .map((id) => `  ${JSON.stringify(id)}: { itemCount: ${stats[id].itemCount}, passThreshold: ${stats[id].passThreshold} },`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/regen-afrikaans-skill-stats.mjs — do not edit by hand.
// Source: data/afrikaans-question-bank.json. Regenerate after authoring changes.
//
// Client-safe summary of the per-skill values AfrikaansSession.tsx needs (item
// count for session length, pass threshold for mastery). The full bank stays
// server-side in lib/afrikaans-selector.ts.

export interface AfrikaansSkillStat {
  itemCount: number;
  passThreshold: number;
}

export const AFRIKAANS_SKILL_STATS: Record<string, AfrikaansSkillStat> = {
${body}
};
`;

fs.writeFileSync(outFile, out, "utf-8");
console.log(`wrote ${outFile} — ${sortedIds.length} skills`);
