// One-shot audit: every Grade 1–3 question that needs a diagram/image, across
// Maths, Afrikaans (FAL), Reading (English) and Life Skills, plus what each
// diagram should depict. Run: node scripts/audit-diagrams-gr1-3.mjs > DIAGRAM_AUDIT_GR1-3.md
import fs from "node:fs";
const R = process.cwd();
const J = (p) => JSON.parse(fs.readFileSync(`${R}/${p}`, "utf8"));
const esc = (s) => String(s ?? "").replace(/\|/g, "\|").replace(/\n/g, " ");
const out = [];
const p = (s = "") => out.push(s);

p(`# Grade 1–3 diagram / image audit`);
p(``);
p(`_Generated by scripts/audit-diagrams-gr1-3.mjs. Lists every Grade 1–3 item that needs a picture, and what the picture must show._`);
p(``);

// ── MATHS ─────────────────────────────────────────────────────────────────────
// Gr1–3 domains = placement gates G1–G3 (M001/M002 Gr1, M003/M020 Gr2, M004/M005 Gr3).
// A maths item needs a diagram only when its `stimulus` is a picture, not text.
const mathsDir = "data/maths-question-banks";
const mFiles = fs.readdirSync(`${R}/${mathsDir}`).filter((f) => f.endsWith(".json"));
const GR123 = { M001:"Gr1 Counting & Cardinality", M002:"Gr1 Counting Sequence",
  M003:"Gr2 Place Value (tens/ones)", M020:"Gr2 Two-Digit Addition",
  M004:"Gr3 Addition (mental)", M005:"Gr3 Subtraction (mental)" };
const BOUNDARY = { M006:"Gr3–4 Multiplication (equal groups)", M007:"Gr3–4 Flexible Decomposition", M028:"Gr3–4 Division" };
const isVisual = (s) => /dot array|number line|picture|array of|ten[- ]frame|blocks|shape|clock|graph|tally|diagram|drawing/i.test(s || "");
const mAll = {};
for (const f of mFiles) { let arr; try { arr = J(`${mathsDir}/${f}`); } catch { continue; }
  for (const q of arr) { if (!GR123[q.domain] && !BOUNDARY[q.domain]) continue;
    (mAll[q.domain] = mAll[q.domain] || []).push(q); } }

p(`## Maths (Grade 1–3)`);
p(``);
let mVisual = [];
for (const dom of Object.keys(GR123)) {
  const items = mAll[dom] || [];
  const vis = items.filter((q) => isVisual(q.stimulus));
  if (vis.length) mVisual.push([dom, vis]);
}
if (!mVisual.length) p(`_No domains beyond counting need diagrams._`);
for (const [dom, vis] of mVisual) {
  const counts = [...new Set(vis.map((q) => (q.stimulus.match(/(\d+)\s*dots/) || [])[1]).filter(Boolean))]
    .map(Number).sort((a,b)=>a-b);
  p(`### ${dom} — ${GR123[dom]} · ${vis.length} items need a diagram`);
  p(``);
  p(`Every item shows a **dot array** the child counts. Distinct dot counts needed: ${counts.join(", ")}.`);
  p(`Layout is "randomised", so these can be auto-generated (SVG of N dots) rather than hand-drawn.`);
  p(``);
  p(`| Domain item id | Stimulus (image to draw) | Answer |`);
  p(`|----|----|----|`);
  for (const q of vis) p(`| ${esc(q.id)} | ${esc(q.stimulus)} | ${esc(q.expectedAnswer)} |`);
  p(``);
}
// Optional / recommended (text now, picture would help)
const m006 = mAll.M006 || [];
p(`### M006 — ${BOUNDARY.M006} · ${m006.length} items (optional pictures)`);
p(``);
p(`These are **word problems presented as text** ("There are 3 bags. Each bag holds 4 apples."). They do **not** require a diagram, but CAPS Foundation Phase usually pairs equal-groups problems with an array/groups picture. Candidate for illustration if you want parity with workbooks.`);
p(``);
p(`> All other Grade 1–3 maths domains (M002 number sequences, M003 place value, M004/M005/M020 arithmetic, M007 decomposition, M028 division) use **text-only stimuli** and need no diagram.`);
p(``);

// ── READING ───────────────────────────────────────────────────────────────────
p(`## Reading / English (Grade 1–3)`);
p(``);
p(`**No diagrams required.** Grade 1–3 reading is Levels L1–L5 (phonics, listening, decoding, comprehension), generated from code pools in the API route. Every item is audio-tap, word-choice or text comprehension — there is no image input type and the reading skill tree contains zero image/picture/diagram references.`);
p(``);

// ── AFRIKAANS ─────────────────────────────────────────────────────────────────
const ab = J("data/afrikaans-question-bank.json");
const aRows = [];
for (const [sid, e] of Object.entries(ab.skills || {})) {
  for (const q of e.questions || []) {
    const needs = q.input_type === "image-match" || (q.image_refs && q.image_refs.length);
    if (needs) aRows.push({ g:e.grade, sid, title:e.title, strand:e.strand, ref:q.ref,
      q:q.question, refs:(q.image_refs||[]).join(", "), exp:q.expected });
  }
}
p(`## Afrikaans FAL (Grade 1–3)`);
p(``);
p(`${aRows.length} items use **image-match** (child hears/reads the Afrikaans word, taps the matching picture). Images are referenced by stable keys in \`image_refs\`; drop assets in \`public/afrikaans/<key>.<ext>\`. Full key→meaning list is in \`scripts/afrikaans-image-manifest.md\`. Until assets exist these fall back to text choices.`);
p(``);
const aByG = {}; for (const r of aRows) (aByG[r.g] = aByG[r.g] || []).push(r);
for (const g of Object.keys(aByG).sort()) {
  p(`### Grade ${g} — ${aByG[g].length} image items`);
  p(``);
  p(`| Skill | Strand | Ref | Question | Image keys (image_refs) |`);
  p(`|----|----|----|----|----|`);
  for (const r of aByG[g]) p(`| ${esc(r.sid)} | ${esc(r.strand)} | ${esc(r.ref)} | ${esc(r.q)} | ${esc(r.refs)} |`);
  p(``);
}

// ── LIFE SKILLS ───────────────────────────────────────────────────────────────
const lb = J("data/life-skills-question-bank.json");
const lRows = [];
for (const [tid, t] of Object.entries(lb.topics || {})) { if (t.grade > 3) continue;
  for (const q of t.questions || []) { if (q.input_type !== "image-match") continue;
    lRows.push({ g:t.grade, tid, title:t.title, ref:q.ref, q:q.question,
      ctx:q.context||"", opts:(q.options||[]).join(" / "), exp:q.expected }); } }
p(`## Life Skills (Grade 1–3)`);
p(``);
p(`${lRows.length} items use **image-match** — the only Life Skills type that hard-requires a picture. Each needs one picture set showing the 4 options (the \`context\` line says exactly what to draw). All sit in the Beginning Knowledge & Health strand.`);
p(``);
const lByG = {}; for (const r of lRows) (lByG[r.g] = lByG[r.g] || []).push(r);
for (const g of Object.keys(lByG).sort()) {
  p(`### Grade ${g} — ${lByG[g].length} image items`);
  p(``);
  p(`| Topic | Ref | Question | Image should show (context) | Correct |`);
  p(`|----|----|----|----|----|`);
  for (const r of lByG[g]) p(`| ${esc(r.tid)} ${esc(r.title)} | ${esc(r.ref)} | ${esc(r.q)} | ${esc(r.ctx)} | ${esc(r.exp)} |`);
  p(``);
}

// ── SUMMARY ───────────────────────────────────────────────────────────────────
p(`## Summary`);
p(``);
p(`| Subject | Grade 1–3 items needing a diagram | Diagram type |`);
p(`|----|----|----|`);
p(`| Maths | ${mVisual.reduce((n,[,v])=>n+v.length,0)} (required) + ${m006.length} optional | Dot arrays (counting); optional equal-groups pictures |`);
p(`| Reading / English | 0 | — none |`);
p(`| Afrikaans FAL | ${aRows.length} | Word→picture match (flat icons / photos) |`);
p(`| Life Skills | ${lRows.length} | 4-option "pick the picture" scenes |`);
p(``);

fs.writeFileSync(`${R}/DIAGRAM_AUDIT_GR1-3.md`, out.join("\n") + "\n");
console.error(`Wrote DIAGRAM_AUDIT_GR1-3.md (${out.length} lines)`);
