// Regenerates lib/matric/paper-index.ts from data/papers/*.json.
// Run via: node scripts/regen-paper-index.mjs
//
// Produces a lightweight PAPER_INDEX (metadata only) shipped to the client,
// plus a switch-based loadPaperById() that dynamic-imports the specific JSON
// file. Each paper becomes its own webpack chunk loaded on demand.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const papersDir = path.join(repoRoot, "data", "papers");
const outFile = path.join(repoRoot, "lib", "matric", "paper-index.ts");

function readJson(file) {
  let raw = fs.readFileSync(file, "utf-8");
  if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1);
  return JSON.parse(raw);
}

const files = fs.readdirSync(papersDir).filter((f) => f.endsWith(".json"));
const entries = [];
for (const file of files) {
  const p = readJson(path.join(papersDir, file));
  if (!p.id || !p.subject) {
    console.warn(`skipping ${file}: missing id or subject`);
    continue;
  }
  const questionCount = Array.isArray(p.questions) ? p.questions.length : 0;
  const subQuestionCount = Array.isArray(p.questions)
    ? p.questions.reduce((s, q) => s + (Array.isArray(q.subQuestions) ? q.subQuestions.length : 0), 0)
    : 0;
  const questionTitles = Array.isArray(p.questions)
    ? p.questions.map((q, i) => ({ number: typeof q.number === "number" ? q.number : i + 1, title: q.title ?? "" }))
    : [];
  entries.push({
    id: p.id,
    file,
    subject: p.subject,
    paperCode: p.paperCode,
    year: p.year,
    session: p.session,
    totalMarks: p.totalMarks,
    durationHours: p.durationHours,
    questionCount,
    subQuestionCount,
    hasQuestionPaper: Boolean(p.questionPaperUrl),
    hasMemo: Boolean(p.memoUrl),
    questionTitles,
  });
}

// Dedupe by id: when two files claim the same id, prefer the one whose
// filename (without .json) matches the id exactly. Warn so dead files get
// noticed.
const byId = new Map();
for (const e of entries) {
  const existing = byId.get(e.id);
  if (!existing) {
    byId.set(e.id, e);
    continue;
  }
  const existingMatchesId = existing.file === `${e.id}.json`;
  const newMatchesId = e.file === `${e.id}.json`;
  if (newMatchesId && !existingMatchesId) {
    console.warn(`dupe id ${e.id}: keeping ${e.file}, dropping ${existing.file}`);
    byId.set(e.id, e);
  } else {
    console.warn(`dupe id ${e.id}: keeping ${existing.file}, dropping ${e.file}`);
  }
}
const deduped = [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));
entries.length = 0;
entries.push(...deduped);

const header = `// AUTO-GENERATED by scripts/regen-paper-index.mjs — do not edit by hand.
// Source: data/papers/*.json. Regenerate after adding/removing a paper.

import type { Paper } from "./papers";

export interface PaperMeta {
  id: string;
  subject: string;
  paperCode: string;
  year: number;
  session: string;
  totalMarks: number;
  durationHours: number;
  questionCount: number;
  subQuestionCount: number;
  hasQuestionPaper: boolean;
  hasMemo: boolean;
  questionTitles: { number: number; title: string }[];
}

export const PAPER_INDEX: PaperMeta[] = [
`;

const indexBody = entries
  .map(
    (e) =>
      `  { id: ${JSON.stringify(e.id)}, subject: ${JSON.stringify(e.subject)}, paperCode: ${JSON.stringify(e.paperCode)}, year: ${e.year}, session: ${JSON.stringify(e.session)}, totalMarks: ${e.totalMarks}, durationHours: ${e.durationHours}, questionCount: ${e.questionCount}, subQuestionCount: ${e.subQuestionCount}, hasQuestionPaper: ${e.hasQuestionPaper}, hasMemo: ${e.hasMemo}, questionTitles: ${JSON.stringify(e.questionTitles)} },`
  )
  .join("\n");

const loaderHeader = `
];

/** Dynamic-import a single paper's full JSON. Each case becomes its own
 *  webpack chunk; only the requested paper is loaded into the client bundle. */
export async function loadPaperById(id: string): Promise<Paper | null> {
  switch (id) {
`;

const loaderBody = entries
  .map((e) => {
    const importPath = `@/data/papers/${e.file}`;
    return `    case ${JSON.stringify(e.id)}: return (await import(${JSON.stringify(importPath)})).default as unknown as Paper;`;
  })
  .join("\n");

const loaderFooter = `
    default: return null;
  }
}
`;

const out = header + indexBody + loaderHeader + loaderBody + loaderFooter;
fs.writeFileSync(outFile, out, "utf-8");
console.log(`wrote ${outFile} — ${entries.length} papers`);
